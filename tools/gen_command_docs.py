#!/usr/bin/env python3
"""Generate the slash-command reference from src/commands.zig.

The hand-written docs/commands.md used to claim "every command is documented"
while missing dozens, including headline features like /pipeline. This script
extracts the `(key, desc, key_hint)` table that the TUI itself uses, so the
reference cannot drift from what the dispatcher actually accepts.

Usage: python3 tools/gen_command_docs.py > docs/commands-generated.md
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "commands.zig"

ROW = re.compile(
    r'\.key = "(/[\w-]+)",\s*\.desc = "([^"]*)"(?:,\s*\.key_hint = "([^"]*)")?'
)


def main() -> int:
    text = SOURCE.read_text()
    rows = ROW.findall(text)
    if not rows:
        print("no commands found", file=sys.stderr)
        return 1

    print("# Command reference (generated)\n")
    print("Generated by `python3 tools/gen_command_docs.py` from `src/commands.zig`.")
    print("Do not edit by hand — the table there is the one the TUI uses.\n")
    print("| Command | Description | Argument / hint |")
    print("|---|---|---|")
    seen = set()
    for key, desc, hint in rows:
        if key in seen:
            continue
        seen.add(key)
        desc = desc.replace("|", "\\|")
        hint_s = ("`" + hint.replace("|", "\\|") + "`") if hint else "—"
        print(f"| `{key}` | {desc} | {hint_s} |")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
