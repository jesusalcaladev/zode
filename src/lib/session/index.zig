//! Session metadata and the list of sessions of one project.
//!
//! There are two things a session needs to be worth listing:
//!
//!   - a NAME, because `zode-2026-10-24T18-12-03.jsonl` is not something a
//!     person recognises three days later;
//!   - an AGE it can read at a glance ("3h", "2mo"), because "which one was the
//!     one I was working on this morning" is the only question the list answers.
//!
//! Both live HERE and not in the session file itself: the `.jsonl` is
//! append-only, compressed line by line (`zjsonl`), and rewriting the head of it
//! to change a name would mean decoding and re-encoding a whole history. So the
//! name goes in a sidecar next to it, `<session>.meta.json`, written temp+rename
//! at 0600 like everything else that is not the user's project.
//!
//! ## There is no index
//!
//! A `<state>/index.json` with a per-project count and a "last session" pointer
//! is a CACHE of what the directory already says, and a cache that can disagree
//! with the truth is how a session list shows a session that no longer exists
//! (deleted, or written by another version). Listing a project means reading one
//! directory; that is a file-system operation, not a network one.

const std = @import("std");
const sessionpath = @import("path.zig");
const zjsonl = @import("../zjsonl.zig");

/// The sidecar next to a session file.
///
/// Two title keys coexist so precedence is structural, not a single string
/// with a source flag (Phase 30.1):
///   - `customTitle`: set by `/rename`. Never overwritten by the AI. Empty =
///     "never custom-named".
///   - `aiTitle`: generated by the AI at turn 3 (Phase 30.2). Ephemeral, safe
///     to regenerate. Empty = "never AI-named".
/// Resolution order: customTitle > aiTitle > firstPrompt > sessionId.
pub const Meta = struct {
    /// User-given name. Empty means "never named": the UI shows the id.
    name: []const u8 = "",
    /// The model the session mostly ran on, for the list's second column.
    model: []const u8 = "",
    /// Unix seconds. 0 means "unknown, use the file's mtime".
    created_at: i64 = 0,
    /// Custom title from `/rename`. Never overwritten by the AI.
    custom_title: []const u8 = "",
    /// AI-generated title (turn 3). Safe to regenerate.
    ai_title: []const u8 = "",
    /// Session tag (readability layer, 35.3). Stored without leading '#'.
    tag: []const u8 = "",
};

/// One session in the list.
pub const Entry = struct {
    /// Full path to the `.jsonl`. This is what a resume needs.
    path: []const u8,
    /// User-given name, or "" when it was never named.
    name: []const u8,
    model: []const u8,
    /// Custom title from /rename (takes precedence).
    custom_title: []const u8,
    /// AI-generated title (turn 3).
    ai_title: []const u8,
    /// Unix seconds: the sidecar's `created_at`, or the file's mtime.
    created_at: i64,

        /// Derived from the session JSONL (head/tail windows, Phase 29.1). Empty when
    /// unknown or not enriched. Owned by the arena/list that produced the entry.
    first_prompt: []const u8 = "",
    last_prompt: []const u8 = "",
    agent_name: []const u8 = "",
    /// File size in bytes (from stat). 0 when unknown.
    size_bytes: u64 = 0,
    /// Session tag (35.3), without leading '#'.
    tag: []const u8 = "",

    /// Total title function (29.3): agentName || customTitle || aiTitle ||
    /// firstPrompt || sessionId[0..8]. A prompt starting with `<tICK>` or that
    /// is empty after trimming is skipped (autonomous/display-hostless). Never
    /// returns an empty slice — "(session)" is the last resort (29.2).
    pub fn title(self: *const Entry, session_id: []const u8) []const u8 {
        if (usablePrompt(self.agent_name)) |pt| return pt;
        if (self.custom_title.len > 0) return self.custom_title;
        if (self.ai_title.len > 0) return self.ai_title;
        if (self.name.len > 0) return self.name;
        if (usablePrompt(self.first_prompt)) |pt| return pt;
        const id = if (session_id.len > 8) session_id[0..8] else session_id;
        if (id.len > 0) return id;
        return "(session)";
    }
};

pub fn usablePrompt(s: []const u8) ?[]const u8 {
    const trimmed = std.mem.trim(u8, s, " \t\r\n");
    if (trimmed.len == 0) return null;
    if (std.mem.startsWith(u8, trimmed, "<tICK>")) return null;
    return trimmed;
}

/// Extracts the JSON string value of `"content"` from one complete JSONL line
/// by string scanning. Returns a view into a decoded buffer the caller provides,
/// or into `line` when no escapes are present. This is NOT a general JSON
/// parser: it handles the session message shape and refuses cut fragments.
fn extractContent(line: []const u8, buf: []u8) ?[]const u8 {
    // Only user/assistant messages carry titles worth showing.
    if (std.mem.indexOf(u8, line, "\"role\":\"user\"") == null and
        std.mem.indexOf(u8, line, "\"role\": \"user\"") == null) return null;
    const needle = "\"content\":\"";
    const at = std.mem.indexOf(u8, line, needle) orelse {
        // Maybe content is not a plain string (array/structured); skip.
        return null;
    };
    var i = at + needle.len;
    var out: usize = 0;
    while (i < line.len and out < buf.len) : (i += 1) {
        const c = line[i];
        if (c == '"') return std.mem.trim(u8, buf[0..out], " \t\r\n");
        if (c == '\\' and i + 1 < line.len) {
            i += 1;
            buf[out] = switch (line[i]) {
                'n' => '\n',
                'r' => '\r',
                't' => '\t',
                '"', '\\', '/' => line[i],
                else => line[i],
            };
            out += 1;
            continue;
        }
        buf[out] = c;
        out += 1;
    }
    return null; // cut fragment / no closing quote
}

/// First user prompt from a session file head, and last from tail (29.1). Reads
/// at most 128KB from each end. A file that cannot be read yields empty strings
/// — the session is still listed (29.2).
pub const TitleHints = struct { first: []const u8 = "", last: []const u8 = "" };

pub fn titleHints(arena: std.mem.Allocator, io: std.Io, path: []const u8) TitleHints {
    var res = TitleHints{};
    var decode: [4096]u8 = undefined;

    // Head (29.1): first complete user prompt.
    const head_data = std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(128 * 1024)) catch null;
    if (head_data) |chunk| {
        var start: usize = 0;
        for (chunk, 0..) |c, i| {
            if (c != '\n') continue;
            const line = chunk[start..i];
            start = i + 1;
            if (extractContent(decompressedLine(arena, line) orelse line, &decode)) |p| {
                if (usablePrompt(p)) |_| {
                    res.first = arena.dupe(u8, std.mem.trim(u8, p, " \t\r\n")) catch res.first;
                    break;
                }
            }
        }
    }

    // Tail (29.1): last user prompt. Read the final window; if it starts
    // mid-line, skip to the first newline.
    const st = std.Io.Dir.cwd().statFile(io, path, .{}) catch return res;
    const size: u64 = st.size;
    if (size > 0) {
        const tail_cap: usize = @intCast(@min(@as(u64, 128 * 1024), size));
        const tail_buf = arena.alloc(u8, tail_cap) catch return res;
        var file = std.Io.Dir.cwd().openFile(io, path, .{}) catch return res;
        defer file.close(io);
        const off: u64 = size - @as(u64, tail_cap);
        const tlen = file.readPositionalAll(io, tail_buf, off) catch 0;
        const chunk = tail_buf[0..tlen];
        var from: usize = 0;
        if (off > 0) {
            if (std.mem.indexOfScalar(u8, chunk, '\n')) |nl| from = nl + 1 else return res;
        }
        var it = std.mem.splitScalar(u8, chunk[from..], '\n');
        while (it.next()) |ln| {
            if (ln.len == 0) continue;
            if (extractContent(decompressedLine(arena, ln) orelse ln, &decode)) |p| {
                if (usablePrompt(p)) |_| {
                    res.last = arena.dupe(u8, std.mem.trim(u8, p, " \t\r\n")) catch res.last;
                }
            }
        }
    }
    return res;
}

fn decompressedLine(arena: std.mem.Allocator, line: []const u8) ?[]const u8 {
    if (!zjsonl.isCompressed(line)) return null;
    return zjsonl.decompressInto(arena, line, 256 * 1024) catch null;
}

/// `<session>.jsonl` → `<session>.meta.json`. The suffix is REPLACED, not
/// appended: `zode-1.jsonl.meta.json` would be a second extension on a file
/// whose name is already a timestamp, and every glob for `*.jsonl` would match
/// the sidecar if it ended in `.json`.
pub fn metaPath(arena: std.mem.Allocator, session_path: []const u8) ![]u8 {
    const suffix = ".jsonl";
    const base = if (std.mem.endsWith(u8, session_path, suffix))
        session_path[0 .. session_path.len - suffix.len]
    else
        session_path;
    return std.fmt.allocPrint(arena, "{s}.meta.json", .{base});
}

/// Reads the sidecar of `session_path` (the `.jsonl`, not the `.meta.json`: the
/// derivation lives in ONE place, `metaPath`). Any problem (missing file,
/// truncated JSON) is "no metadata", never an error: a session whose name
/// cannot be read still has to appear in the list, with its path and its age.
pub fn readMeta(arena: std.mem.Allocator, io: std.Io, session_path: []const u8) Meta {
    // Use a throwaway ArenaAllocator on page_allocator for all temporary
    // allocations (meta path, file data, JSON tree). Everything that must
    // outlive this function is copied into `arena` below.
    var tmp_state = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer tmp_state.deinit();
    const tmp = tmp_state.allocator();
    const mp = metaPath(tmp, session_path) catch return .{};
    const data = std.Io.Dir.cwd().readFileAlloc(io, mp, tmp, .limited(8 * 1024)) catch return .{};
    const parsed = parseMeta(tmp, data);
    var result = Meta{};
    if (parsed.name.len > 0) result.name = arena.dupe(u8, parsed.name) catch "";
    if (parsed.model.len > 0) result.model = arena.dupe(u8, parsed.model) catch "";
    result.created_at = parsed.created_at;
    if (parsed.custom_title.len > 0) result.custom_title = arena.dupe(u8, parsed.custom_title) catch "";
    if (parsed.ai_title.len > 0) result.ai_title = arena.dupe(u8, parsed.ai_title) catch "";
    if (parsed.tag.len > 0) result.tag = arena.dupe(u8, parsed.tag) catch "";
    return result;
}

/// The pure half of `readMeta`, so the parsing has a test that does not need a
/// file system.
pub fn parseMeta(arena: std.mem.Allocator, data: []const u8) Meta {
    const parsed = std.json.parseFromSliceLeaky(std.json.Value, arena, data, .{}) catch return .{};
    if (parsed != .object) return .{};
    const o = parsed.object;
    var meta = Meta{};
    if (o.get("name")) |v| {
        if (v == .string) meta.name = v.string;
    }
    if (o.get("model")) |v| {
        if (v == .string) meta.model = v.string;
    }
    if (o.get("created_at")) |v| {
        if (v == .integer) meta.created_at = v.integer;
    }
    if (o.get("custom_title")) |v| {
        if (v == .string) meta.custom_title = v.string;
    }
    if (o.get("ai_title")) |v| {
        if (v == .string) meta.ai_title = v.string;
    }
    if (o.get("tag")) |v| {
        if (v == .string) meta.tag = v.string;
    }
    return meta;
}

/// Writes the sidecar for `session_path`, atomically (temp + rename, 0600), the
/// way `auth.json` is written: a half-written sidecar left by a crash would be
/// read as "no name" forever, because parsing failure is not an error.
///
/// It takes the SESSION path and derives the sidecar with `metaPath`, instead of
/// taking the sidecar path: the first version took the sidecar, and one caller
/// passing the session path renamed the metadata OVER the `.jsonl`. The test
/// caught it (the file stopped existing where the session was), and the lesson
/// is that the API should not make that mistake expressible.
pub fn writeMeta(io: std.Io, arena: std.mem.Allocator, session_path: []const u8, meta: Meta) !void {
    const path = try metaPath(arena, session_path);
    defer arena.free(path);
    const tmp = try std.fmt.allocPrint(arena, "{s}.tmp", .{path});
    defer arena.free(tmp);
    var file = std.Io.Dir.cwd().createFile(io, tmp, .{
        .truncate = true,
        .permissions = sessionpath.session_mode,
    }) catch |err| return err;
    file.setPermissions(io, sessionpath.session_mode) catch {};
    {
        var wbuf: [1024]u8 = undefined;
        var fw = file.writer(io, &wbuf);
        var w = &fw.interface;
        try w.writeAll("{\"name\":");
        try writeJsonString(w, meta.name);
        try w.writeAll(",\"model\":");
        try writeJsonString(w, meta.model);
        try w.print(",\"created_at\":{d}", .{meta.created_at});
        try writeMetaTitles(w, meta);
        try w.writeAll("}\n");
        fw.interface.flush() catch |err| {
            file.close(io);
            _ = std.Io.Dir.cwd().deleteFile(io, tmp) catch {};
            return err;
        };
    }
    file.close(io);
    try std.Io.Dir.rename(.cwd(), tmp, .cwd(), path, io);
}

fn writeMetaJson(w: *std.Io.Writer, meta: Meta) !void {
    try w.writeAll("{\"name\":");
    try writeJsonString(w, meta.name);
    try w.writeAll(",\"model\":");
    try writeJsonString(w, meta.model);
    try w.print(",\"created_at\":{d}}}\n", .{meta.created_at});
}


/// Writes the title/tag fields (custom_title, ai_title, tag) into a JSON object
/// that is already open. Appends `,"custom_title":...,"ai_title":...,"tag":...`
/// before the closing brace. The caller must write the opening `{` and other
/// fields first, and the closing `}` after.
pub fn writeMetaTitles(w: *std.Io.Writer, meta: Meta) !void {
    try w.writeAll(",\"custom_title\":");
    try writeJsonString(w, meta.custom_title);
    try w.writeAll(",\"ai_title\":");
    try writeJsonString(w, meta.ai_title);
    try w.writeAll(",\"tag\":");
    try writeJsonString(w, meta.tag);
}

fn writeJsonString(w: *std.Io.Writer, s: []const u8) !void {
    try w.writeAll("\"");
    var start: usize = 0;
    for (s, 0..) |c, i| {
        const esc: ?[]const u8 = switch (c) {
            '"' => "\\\"",
            '\\' => "\\\\",
            '\n' => "\\n",
            '\r' => "\\r",
            '\t' => "\\t",
            else => null,
        };
        const e = esc orelse continue;
        if (i > start) try w.writeAll(s[start..i]);
        try w.writeAll(e);
        start = i + 1;
    }
    if (start < s.len) try w.writeAll(s[start..]);
    try w.writeAll("\"");
}

/// Every session in `dir_path`, NEWEST FIRST.
///
/// Phase 1 (29.1): stat + meta sidecar per session (no JSONL inflation). Phase 2:
/// head+tail title hints for the first 50 sessions that still lack a resolved
/// title, so the picker shows meaningful names. A missing directory is an empty
/// list. 29.2: an unreadable file never drops the entry — it keeps its path/id
/// and `Entry.title()` falls back to "(session)".
pub fn scan(arena: std.mem.Allocator, io: std.Io, dir_path: []const u8) []Entry {
    var dir = std.Io.Dir.cwd().openDir(io, dir_path, .{ .iterate = true }) catch return &.{};
    defer dir.close(io);

    var list: std.ArrayList(Entry) = .empty;
    var it = dir.iterate();
    while (it.next(io) catch null) |e| {
        if (e.kind == .directory) continue;
        if (!sessionpath.isSessionFile(e.name)) continue;

        const path = std.fs.path.join(arena, &.{ dir_path, e.name }) catch continue;
        var mtime: i64 = 0;
        var size_bytes: u64 = 0;
        if (dir.statFile(io, e.name, .{})) |st| {
            mtime = st.mtime.toSeconds();
            size_bytes = st.size;
        } else |_| {}

        var name: []const u8 = "";
        var model: []const u8 = "";
        var custom_title: []const u8 = "";
        var ai_title: []const u8 = "";
        var tag: []const u8 = "";
        var created: i64 = 0;
        const meta = readMeta(arena, io, path);
        if (meta.name.len > 0) name = meta.name;
        if (meta.model.len > 0) model = meta.model;
        if (meta.custom_title.len > 0) custom_title = meta.custom_title;
        if (meta.ai_title.len > 0) ai_title = meta.ai_title;
        if (meta.tag.len > 0) tag = meta.tag;
        if (meta.created_at > 0) created = meta.created_at;
        if (created == 0) created = mtime;

        list.append(arena, .{
            .path = path,
            .name = name,
            .model = model,
            .custom_title = custom_title,
            .ai_title = ai_title,
            .created_at = created,
            .size_bytes = size_bytes,
            .tag = tag,
        }) catch continue;
    }

    std.mem.sort(Entry, list.items, {}, newerFirst);
    // Phase 2: enrich first 50 with head/tail prompt hints when no explicit title.
    const enrich_n = @min(list.items.len, 50);
    for (list.items[0..enrich_n]) |*ent| {
        if (ent.custom_title.len > 0 or ent.ai_title.len > 0 or ent.name.len > 0) continue;
        const hints = titleHints(arena, io, ent.path);
        ent.first_prompt = hints.first;
        ent.last_prompt = hints.last;
    }
    return list.items;
}

fn newerFirst(_: void, a: Entry, b: Entry) bool {
    if (a.created_at != b.created_at) return a.created_at > b.created_at;
    // Same second (two sessions created by a script): the path decides, so the
    // order is stable between two openings of the list instead of whatever the
    // directory happened to return.
    return std.mem.lessThan(u8, a.path, b.path);
}

/// How long ago, in the shortest unit that is still true: `now`, `42s`, `12m`,
/// `3h`, `2d`, `3w`, `4mo`, `2y`.
///
/// `mo` and not `m` for months: with `m` already meaning minutes, `3m` and `3m`
/// are two different ages that read the same.
pub fn ageLabel(now: i64, then: i64, buf: []u8) []const u8 {
    const d = now - then;
    if (d <= 1) return std.fmt.bufPrint(buf, "now", .{}) catch "now";
    const s: u64 = @intCast(d);
    const pair: struct { n: u64, unit: []const u8 } = if (s < 60)
        .{ .n = s, .unit = "s" }
    else if (s < 3600)
        .{ .n = s / 60, .unit = "m" }
    else if (s < 86_400)
        .{ .n = s / 3600, .unit = "h" }
    else if (s < 7 * 86_400)
        .{ .n = s / 86_400, .unit = "d" }
    else if (s < 30 * 86_400)
        .{ .n = s / (7 * 86_400), .unit = "w" }
    else if (s < 365 * 86_400)
        .{ .n = s / (30 * 86_400), .unit = "mo" }
    else
        .{ .n = s / (365 * 86_400), .unit = "y" };
    return std.fmt.bufPrint(buf, "{d}{s}", .{ pair.n, pair.unit }) catch "?";
}

