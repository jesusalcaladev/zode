const t = std.testing;

test "metaPath: replaces .jsonl, does not append" {
    var arena_state = std.heap.ArenaAllocator.init(t.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    try t.expectEqualStrings(
        "/state/sessions/abc/zode-1.meta.json",
        try metaPath(a, "/state/sessions/abc/zode-1.jsonl"),
    );
    // A path without the suffix gets it too, instead of losing characters.
    try t.expectEqualStrings("/tmp/zode-1.meta.json", try metaPath(a, "/tmp/zode-1"));
}

test "parseMeta: the three fields, and garbage is 'no metadata'" {
    var arena_state = std.heap.ArenaAllocator.init(t.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    const m = parseMeta(a, "{\"name\":\"fix the parser\",\"model\":\"glm-5.3\",\"created_at\":1761234567}");
    try t.expectEqualStrings("fix the parser", m.name);
    try t.expectEqualStrings("glm-5.3", m.model);
    try t.expectEqual(1761234567, m.created_at);

    // A name with an escaped quote survives the round trip of the writer below.
    const empty = parseMeta(a, "not json at all");
    try t.expectEqualStrings("", empty.name);
    try t.expectEqual(@as(i64, 0), empty.created_at);
    try t.expectEqualStrings("", empty.custom_title);
    try t.expectEqualStrings("", empty.ai_title);
}

test "parseMeta: reads custom_title and ai_title" {
    var arena_state = std.heap.ArenaAllocator.init(t.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();

    const m = parseMeta(a, "{\"name\":\"fix\",\"model\":\"glm-5.3\",\"created_at\":1761234567,\"custom_title\":\"my fix\",\"ai_title\":\"parser fix\"}");
    try t.expectEqualStrings("my fix", m.custom_title);
    try t.expectEqualStrings("parser fix", m.ai_title);
    // custom_title wins over ai_title
    const combo = parseMeta(a, "{\"custom_title\":\"custom\",\"ai_title\":\"ai\"}");
    try t.expectEqualStrings("custom", combo.custom_title);
    try t.expectEqualStrings("ai", combo.ai_title);
}

test "writeMetaTitles writes custom_title and ai_title into open object" {
    var buf: [512]u8 = undefined;
    var w: std.Io.Writer = .fixed(&buf);
    try w.writeAll("{\"name\":\"fix\",\"model\":\"glm-5.3\",\"created_at\":5");
    try writeMetaTitles(&w, .{ .custom_title = "my fix", .ai_title = "parser fix" });
    try w.writeAll("}\n");
    const out = w.buffered();

    var arena_state = std.heap.ArenaAllocator.init(t.allocator);
    defer arena_state.deinit();
    const back = parseMeta(arena_state.allocator(), out);
    try t.expectEqualStrings("fix", back.name);
    try t.expectEqualStrings("glm-5.3", back.model);
    try t.expectEqualStrings("my fix", back.custom_title);
    try t.expectEqualStrings("parser fix", back.ai_title);
    try t.expectEqual(@as(i64, 5), back.created_at);
}

